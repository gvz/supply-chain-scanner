//! Which paths in an unpacked artifact execute when a developer
//! installs or first imports it, per ecosystem.
//!
//! Deliberately *not* a method on `Ecosystem`: that trait carries
//! `simple_page` and `download`, so implementing it requires an
//! `Upstream`, an index cache and a configuration — none of which exist
//! inside the sandbox, where the collector runs with no network, no
//! database and no config file. This is the dependency-free slice of
//! ecosystem knowledge the collector actually needs.
//!
//! [`PyPiInstallSurface`] decides on the path shape alone. Console-script
//! wrappers are generated by pip at install time and are not in the
//! artifact at all, so declared entry points contribute nothing here;
//! the collector covers the modules they name through the collection
//! order (Task 3).

use std::path::{Component, Path};
use std::str::FromStr;

use pep440_rs::Version;

/// File names, at the unpacked root, that execute at sdist build time
/// or at Python interpreter startup, before any ordinary module of the
/// package runs.
const ROOT_INSTALL_FILE_NAMES: &[&str] = &[
    "setup.py", //
    "setup.cfg",
    "pyproject.toml",
    "sitecustomize.py",
    "usercustomize.py",
];

/// The data tree a wheel carries at its root, named
/// `<name>-<version>.data`. Only its `scripts` child matters here.
const WHEEL_DATA_SUFFIX: &str = ".data";
/// The directory inside a wheel's data tree whose files pip installs
/// onto the developer's `PATH` as executables.
const WHEEL_SCRIPTS_DIR: &str = "scripts";

/// The paths, relative to the unpacked crate root, that execute when a
/// developer builds or runs the crate: the build script runs before the
/// crate compiles, and the library root and binary root run when a
/// dependent crate or the developer calls into them.
const CARGO_INSTALL_FILE_NAMES: &[&str] = &[
    "build.rs", //
    "src/lib.rs",
    "src/main.rs",
];

/// The `__init__.py` file name. Only the top-level copy counts as
/// install surface: importing the package runs it, but sub-package
/// `__init__.py` files run only when the importer also imports that
/// sub-package, so they stay ordinary modules.
const PACKAGE_INIT_FILE: &str = "__init__.py";

/// Returns the file name extension in lower case, with no leading dot.
/// An empty extension counts as missing, so `foo` and `foo.` have no
/// extension.
fn extension_of(path: &Path) -> Option<String> {
    path.extension()
        .and_then(|ext| ext.to_str())
        .map(str::to_ascii_lowercase)
}

/// Which paths in an unpacked artifact execute when a developer
/// installs or first imports it.
pub trait InstallSurface: Send + Sync {
    fn is_install_surface(&self, relative_path: &Path) -> bool;
}

/// The Python rules. `relative_path` must be relative to the unpacked
/// artifact root; a path that is absolute or escapes the root answers
/// `false`, because it names no location in the artifact.
pub struct PyPiInstallSurface;

impl InstallSurface for PyPiInstallSurface {
    fn is_install_surface(&self, relative_path: &Path) -> bool {
        // Only normal components name locations inside the artifact.
        // Reject `..`, absolute paths, and prefix separators alike.
        let mut components = Vec::new();
        for component in relative_path.components() {
            match component {
                Component::Normal(name) => components.push(name.to_string_lossy().into_owned()),
                Component::CurDir => continue,
                _ => return false,
            }
        }

        if matches_wheel_shape(&components) {
            return true;
        }

        // A wheel's top-level entries are the package itself: `pkg/`,
        // `pkg-1.0.data/`. An sdist unpacks with its `<name>-<version>`
        // directory still wrapping everything (`src/plugin/unpack.rs`
        // does no prefix stripping), so `setup.py` sits at
        // `demo-1.0/setup.py` and the package's own `__init__.py` at
        // `demo-1.0/demo/__init__.py` — one level deeper than the wheel
        // shape above checks. Re-check the remainder once the leading
        // component looks like that directory, recognized by a PEP 440
        // version suffix (the same parser this proxy already uses for
        // advisory matching) rather than by name alone, which would
        // also match an ordinary package directory that happens to
        // contain a file named `setup.py`.
        if components.len() > 1 && looks_like_sdist_root(&components[0]) {
            return matches_wheel_shape(&components[1..]);
        }

        false
    }
}

/// The Rust rules. `relative_path` must be relative to the unpacked
/// crate root; a path that is absolute or escapes the root answers
/// `false`, because it names no location in the crate.
///
/// A proc-macro entry point beyond `src/lib.rs` is not detected here:
/// that check needs the contents of `Cargo.toml`, which this path-only
/// trait cannot see.
pub struct CargoInstallSurface;

impl InstallSurface for CargoInstallSurface {
    fn is_install_surface(&self, relative_path: &Path) -> bool {
        // Only normal components name locations inside the crate.
        // Reject `..`, absolute paths, and prefix separators alike.
        let mut components = Vec::new();
        for component in relative_path.components() {
            match component {
                Component::Normal(name) => components.push(name.to_string_lossy().into_owned()),
                Component::CurDir => continue,
                _ => return false,
            }
        }

        let joined = components.join("/");
        CARGO_INSTALL_FILE_NAMES.contains(&joined.as_str())
    }
}

/// Whether `components` names install surface under the wheel shape:
/// a root-level entry point or `.pth` file, a top-level `__init__.py`,
/// or a file under `<name>-<version>.data/scripts/`.
fn matches_wheel_shape(components: &[String]) -> bool {
    match components.len() {
        1 => {
            let first = components[0].as_str();
            ROOT_INSTALL_FILE_NAMES.contains(&first)
                || extension_of(Path::new(first)).as_deref() == Some("pth")
        }
        2 => {
            components[1].as_str() == PACKAGE_INIT_FILE
                && !components[0].ends_with(WHEEL_DATA_SUFFIX)
        }
        n if n >= 3 => {
            components[0].ends_with(WHEEL_DATA_SUFFIX)
                && components[1].as_str() == WHEEL_SCRIPTS_DIR
        }
        _ => false,
    }
}

/// Whether `name` looks like an sdist's `<project>-<version>` root
/// directory: some suffix after a `-` parses as a PEP 440 version.
/// Tries progressively earlier hyphens so a project name that itself
/// contains one (`my-project-1.0`) still resolves.
fn looks_like_sdist_root(name: &str) -> bool {
    let mut search_from = name.len();
    while let Some(idx) = name[..search_from].rfind('-') {
        if Version::from_str(&name[idx + 1..]).is_ok() {
            return true;
        }
        search_from = idx;
    }
    false
}

/// Resolves an ecosystem id (the one from
/// [`crate::ecosystem::traits::Ecosystem::id`]) to its install surface.
/// `None` means this binary does not know the ecosystem, so it cannot
/// review any artifact of it.
///
/// The table is small, static, and lifetime-bound to this module, so
/// the resolved surface stays valid for the whole process and needs no
/// allocation or initialization at scan time.
pub fn install_surface_for(ecosystem_id: &str) -> Option<&'static dyn InstallSurface> {
    static PYPI: PyPiInstallSurface = PyPiInstallSurface;
    static CARGO: CargoInstallSurface = CargoInstallSurface;
    static SURFACES: &[(&str, &dyn InstallSurface)] = &[("pypi", &PYPI), ("cargo", &CARGO)];

    SURFACES
        .iter()
        .find(|(id, _)| *id == ecosystem_id)
        .map(|(_, surface)| *surface)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pypi_install_surface_matches_sdist_build_entry_points() {
        for path in ["setup.py", "setup.cfg", "pyproject.toml"] {
            assert!(
                PyPiInstallSurface.is_install_surface(Path::new(path)),
                "{path} was not an install surface"
            );
        }
    }

    #[test]
    fn pypi_install_surface_matches_pth_and_customize_files() {
        for path in ["foo.pth", "distutils-precedence.pth"] {
            assert!(
                PyPiInstallSurface.is_install_surface(Path::new(path)),
                "{path} was not an install surface"
            );
        }
        for path in ["sitecustomize.py", "usercustomize.py"] {
            assert!(
                PyPiInstallSurface.is_install_surface(Path::new(path)),
                "{path} was not an install surface"
            );
        }
    }

    #[test]
    fn pypi_install_surface_matches_wheel_data_scripts() {
        assert!(
            PyPiInstallSurface.is_install_surface(Path::new("pkg-1.0.data/scripts/postinstall"))
        );
    }

    #[test]
    fn pypi_install_surface_matches_top_level_dunder_init() {
        assert!(PyPiInstallSurface.is_install_surface(Path::new("pkg/__init__.py")));
    }

    #[test]
    fn pypi_install_surface_skips_nested_dunder_init() {
        assert!(!PyPiInstallSurface.is_install_surface(Path::new("pkg/sub/__init__.py")));
    }

    #[test]
    fn pypi_install_surface_skips_ordinary_modules() {
        assert!(!PyPiInstallSurface.is_install_surface(Path::new("pkg/util.py")));
    }

    #[test]
    fn install_surface_for_resolves_pypi() {
        let surface = install_surface_for("pypi");
        assert!(
            surface.is_some(),
            "pypi did not resolve to an install surface"
        );
    }

    #[test]
    fn install_surface_for_returns_none_for_an_unknown_ecosystem() {
        assert!(install_surface_for("npm").is_none());
    }

    #[test]
    fn cargo_install_surface_matches_a_root_build_script() {
        assert!(CargoInstallSurface.is_install_surface(Path::new("build.rs")));
    }

    #[test]
    fn cargo_install_surface_matches_the_root_lib_and_main_entry_points() {
        assert!(CargoInstallSurface.is_install_surface(Path::new("src/lib.rs")));
        assert!(CargoInstallSurface.is_install_surface(Path::new("src/main.rs")));
    }

    #[test]
    fn cargo_install_surface_does_not_match_an_ordinary_module() {
        assert!(!CargoInstallSurface.is_install_surface(Path::new("src/parser.rs")));
    }

    #[test]
    fn cargo_install_surface_rejects_paths_that_escape_the_root() {
        assert!(!CargoInstallSurface.is_install_surface(Path::new("../../etc/passwd")));
    }

    #[test]
    fn install_surface_for_resolves_cargo() {
        let surface = install_surface_for("cargo");
        assert!(
            surface.is_some(),
            "cargo did not resolve to an install surface"
        );
        assert!(surface
            .expect("cargo surface")
            .is_install_surface(Path::new("build.rs")));
    }

    #[test]
    fn pypi_install_surface_matches_sdist_root_entry_points() {
        for path in [
            "demo-1.0/setup.py",
            "demo-1.0/setup.cfg",
            "demo-1.0/pyproject.toml",
        ] {
            assert!(
                PyPiInstallSurface.is_install_surface(Path::new(path)),
                "{path} was not an install surface"
            );
        }
    }

    #[test]
    fn pypi_install_surface_matches_sdist_root_top_level_dunder_init() {
        assert!(PyPiInstallSurface.is_install_surface(Path::new("demo-1.0/demo/__init__.py")));
    }

    #[test]
    fn pypi_install_surface_skips_ordinary_modules_inside_an_sdist_root() {
        assert!(!PyPiInstallSurface.is_install_surface(Path::new("demo-1.0/demo/util.py")));
    }

    #[test]
    fn pypi_install_surface_recognizes_a_project_name_that_itself_contains_a_hyphen() {
        assert!(PyPiInstallSurface.is_install_surface(Path::new("my-demo-1.0/setup.py")));
    }

    #[test]
    fn pypi_install_surface_does_not_treat_an_ordinary_package_directory_as_an_sdist_root() {
        // "pkg" carries no version suffix, so this must not be
        // reinterpreted as a wrapped sdist — it is just a module that
        // happens to be named like an entry point, inside a package.
        assert!(!PyPiInstallSurface.is_install_surface(Path::new("pkg/setup.py")));
    }
}
